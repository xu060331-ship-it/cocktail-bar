/**
 * 获取完整 persona（id + system prompt + 共享规则）
 */
function getPersona(personaId) {
  const persona = PERSONAS[personaId]
  if (!persona) return null
  return {
    ...persona,
    fullPrompt: persona.systemPrompt + SHARED_RULES,
  }
}

/**
 * 获取所有 persona 列表（不含完整 prompt，只给前端展示用）
 */
function listPersonas() {
  return Object.values(PERSONAS).map(p => ({
    id: p.id,
    name: p.name,
    emoji: p.emoji,
    avatar: p.avatar,
    color: p.color,
    label: p.label,
    description: p.description,
  }))
}

